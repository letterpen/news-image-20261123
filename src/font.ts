export const GLYPH_W = 7;
export const GLYPH_H = 9;

export function charWidth(scale: number): number {
  return (GLYPH_W + 1) * scale;
}

export function textWidth(text: string, scale: number): number {
  let w = 0;
  for (const ch of text) {
    const g = GLYPHS[ch] ?? GLYPHS["?"];
    void g;
    w += charWidth(scale);
  }
  return w > 0 ? w - scale : 0;
}

// Draw one glyph's ink pixels as scale x scale blocks.
export function drawGlyph(
  cv: { set(x: number, y: number, c: number): void },
  ch: string,
  x: number,
  y: number,
  scale: number,
  color: number,
): void {
  const g = GLYPHS[ch] ?? GLYPHS["?"];
  for (let r = 0; r < GLYPH_H; r++) {
    const row = g[r];
    for (let c = 0; c < GLYPH_W; c++) {
      if (row[c] === "#") {
        for (let dy = 0; dy < scale; dy++) {
          for (let dx = 0; dx < scale; dx++) {
            cv.set(x + c * scale + dx, y + r * scale + dy, color);
          }
        }
      }
    }
  }
}

export function drawText(
  cv: { set(x: number, y: number, c: number): void },
  text: string,
  x: number,
  y: number,
  scale: number,
  color: number,
): number {
  let cx = x;
  for (const ch of text) {
    drawGlyph(cv, ch, cx, y, scale, color);
    cx += charWidth(scale);
  }
  return cx;
}

// Greedy word wrap. Returns lines that fit maxWidth px.
export function wrapText(text: string, maxWidth: number, scale: number): string[] {
  const words = text.split(" ");
  const lines: string[] = [];
  let cur = "";
  for (const w of words) {
    const trial = cur === "" ? w : cur + " " + w;
    if (textWidth(trial, scale) <= maxWidth || cur === "") {
      cur = trial;
    } else {
      lines.push(cur);
      cur = w;
    }
  }
  if (cur !== "") lines.push(cur);
  return lines;
}
