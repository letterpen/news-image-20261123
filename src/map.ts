const LAND = [NORTH_AMERICA, GREENLAND, SOUTH_AMERICA, AFRICA, EURASIA, UK, JAPAN, AUSTRALIA, NEW_ZEALAND, MADAGASCAR];

export interface MapBox { x: number; y: number; w: number; h: number }

function project(lon: number, lat: number, box: MapBox): [number, number] {
  const x = box.x + ((lon + 180) / 360) * box.w;
  const y = box.y + ((80 - lat) / 135) * box.h;
  return [x, y];
}

export function drawWorldMap(
  cv: Canvas,
  box: MapBox,
  pins: Array<{ n: number; lon: number; lat: number }>,
  ocean: number,
  land: number,
  landEdge: number,
  pinFill: number,
  pinText: number,
): void {
  cv.rect(box.x, box.y, box.w, box.h, ocean);
  for (const poly of LAND) {
    const pts = poly.map(([lo, la]) => project(lo, la, box));
    cv.filledPolygon(pts, land);
    cv.polygonOutline(pts, landEdge);
  }
  // Indonesia as a chain of small islands.
  for (const [lo, la] of INDONESIA) {
    const [x, y] = project(lo, la, box);
    cv.filledCircle(x, y, 2, land);
  }
  // Equator + tropics guides, faint.
  const eq = project(0, 0, box)[1];
  for (let x = box.x; x < box.x + box.w; x += 6) cv.set(x, Math.round(eq), rgb(255, 255, 255));
  // Pins: red discs with white numbers (bigger disc for two-digit numbers).
  for (const p of pins) {
    const [x, y] = project(p.lon, p.lat, box);
    const s = String(p.n);
    const r = s.length > 1 ? 7 : 6;
    cv.filledCircle(x, y, r, pinFill);
    cv.circleOutline(x, y, r, 0xffffff, 2);
    const tw = s.length * 8 - 1;
    // draw number at scale 1, centred
    const gx = Math.round(x - tw / 2);
    const gy = Math.round(y - 4);
    drawPinNumber(cv, s, gx, gy, pinText);
  }
}

import { drawText } from "./font.ts";
function drawPinNumber(cv: Canvas, s: string, x: number, y: number, c: number): void {
  drawText(cv, s, x, y, 1, c);
}
